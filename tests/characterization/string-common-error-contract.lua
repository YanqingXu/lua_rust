local function must_fail(fn, ...)
    local ok, err = pcall(fn, ...)
    assert(not ok and type(err) == 'string')
end

must_fail(string.find, 'abc', 'a', {})
must_fail(string.byte, 'abc', {})
must_fail(string.char, 256)
must_fail(string.gsub, {}, 'a', 'b')
must_fail(string.match, 'abc', 'a', false)
must_fail(string.sub, 'abc', {})
must_fail(string.rep, 'abc', false)
must_fail(string.format, '%s', {})
must_fail(string.format, '%q', false)
must_fail(string.gsub, 'a', 'a', '%2')
must_fail(string.find, 'abc', '(')
must_fail(string.match, 'abc', '%1')
assert(string.byte('abc') == 97)
assert(string.byte('abc', ' 2 ') == 98)
assert(string.byte('abc', '0x2') == 98)
assert(string.char(255.75, -0.75) == string.char(255, 0))
assert(string.find('[', '[', 1, true) == 1)
assert(string.format('%u/%x', -1, -1) == '4294967295/ffffffff')
assert(select('#', string.byte('abc', 4)) == 0)
assert(select('#', string.find('abc', 'b')) == 2)
assert(select('#', string.find('abc', 'z')) == 1)
assert(select('#', string.gsub('aba', 'a', 'x')) == 2)
local token = {}
local ok, err = pcall(string.gsub, 'a', '.', function() error(token) end)
assert(not ok and rawequal(err, token))
local co = coroutine.create(function() string.char(256) end)
ok, err = coroutine.resume(co)
assert(not ok and type(err) == 'string' and coroutine.status(co) == 'dead')
print('string common error contract passed')
